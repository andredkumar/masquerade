/**
 * Round 2A — `shared/automask/constants.ts` is GENERATED, not typed (AUTOMASK_2A_GO.md §2).
 *
 *   python3 scripts/automask_spike/automask_spike.py --dump-constants > /tmp/automask_constants.json
 *   npx tsx scripts/automask_eval/gen-constants.ts /tmp/automask_constants.json
 *
 * Reads the JSON the frozen Python spike prints and writes shared/automask/constants.ts. The unit test
 * (server/services/__tests__/automask.constants.test.ts) re-reads the JSON and asserts every key matches, so the
 * port cannot drift from the frozen values without the test saying so.
 */
import { readFileSync, writeFileSync } from 'fs';
import path from 'path';

const src = process.argv[2];
if (!src) { console.error('usage: gen-constants.ts <automask_constants.json>'); process.exit(2); }
const dump = JSON.parse(readFileSync(src, 'utf8')) as Record<string, unknown>;
const rules = dump.RULES as Record<string, boolean>;
const scalars = Object.keys(dump).filter((k) => k !== 'RULES' && !k.startsWith('_')).sort();

const lit = (v: unknown) => (typeof v === 'string' ? JSON.stringify(v) : String(v));
const lines: string[] = [];
lines.push('// GENERATED by scripts/automask_eval/gen-constants.ts from `automask_spike.py --dump-constants` — do not edit.');
lines.push(`// Source: ${dump._source} · frozen ${dump._frozen} · see scripts/automask_spike/CONSTANTS.md for what each value means.`);
lines.push('');
lines.push('export const AUTOMASK_CONSTANTS = {');
for (const k of scalars) lines.push(`  ${k}: ${lit(dump[k])},`);
lines.push('} as const;');
lines.push('');
lines.push('export const RULES = {');
for (const k of Object.keys(rules).sort()) lines.push(`  ${k}: ${rules[k]},`);
lines.push('} as const;');
lines.push('');
lines.push(`export const CONSTANTS_FROZEN = ${JSON.stringify(dump._frozen)};`);
lines.push('');
const out = path.resolve(process.cwd(), 'shared/automask/constants.ts');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${scalars.length} constants, ${Object.keys(rules).length} rules`);
